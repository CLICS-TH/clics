const DECLARED_KEYS = ['notes', 'target', 'providers', ...Object.keys(POLICY.LOCAL_INSTANCES)];
const INSTANCE_KEYS = ['role', 'model', 'engine', 'system_fingerprint', 'source'];

function walkStrings(value, at, fn) {
  if (typeof value === 'string') fn(value, at);
  else if (Array.isArray(value)) value.forEach((v, i) => walkStrings(v, `${at}[${i}]`, fn));
  else if (value && typeof value === 'object') for (const [k, v] of Object.entries(value)) walkStrings(v, `${at}.${k}`, fn);
}

// Throws on anything the manifest cannot honestly carry: an unknown key, a provider that may not serve
// the purpose it is declared for, or a string that looks like an address or a key.
function validateDeclared(declared) {
  if (!declared || typeof declared !== 'object' || Array.isArray(declared)) throw new TypeError('declared: must be an object');
  for (const k of Object.keys(declared)) {
    if (!DECLARED_KEYS.includes(k)) throw new TypeError(`declared: unknown key "${k}" (allowed: ${DECLARED_KEYS.join(', ')})`);
  }
  const providers = declared.providers ?? {};
  for (const [purpose, name] of Object.entries(providers)) {
    if (!POLICY.PURPOSES.includes(purpose)) throw new TypeError(`declared.providers: "${purpose}" is not a purpose (${POLICY.PURPOSES.join(', ')})`);
    if (name === null) continue;
    if (!POLICY.PROVIDER_NAMES.includes(name)) throw new TypeError(`declared.providers.${purpose}: "${name}" is not a provider (${POLICY.PROVIDER_NAMES.join(', ')})`);
    if (!POLICY.servesPurpose(name, purpose)) throw new TypeError(`declared.providers.${purpose}: "${name}" may not serve ${purpose}`);
  }
  for (const name of Object.keys(POLICY.LOCAL_INSTANCES)) {
    const inst = declared[name];
    if (inst == null) continue;
    for (const k of Object.keys(inst)) {
      if (!INSTANCE_KEYS.includes(k)) throw new TypeError(`declared.${name}: unknown key "${k}" (allowed: ${INSTANCE_KEYS.join(', ')})`);
    }
  }
  walkStrings(declared, 'declared', (s, at) => {
    if (isUnsafeString(s)) throw new TypeError(`${at}: looks like an address or a key — declared values appear in the drift report on the unauthenticated /health/deep, so it may carry neither`);
  });
  sortKeys(declared, 'declared');   // JSON-clean, or a TypeError naming the path
  return declared;
}

function buildManifest(declared) {
  const body = { schema: SCHEMA, expected: { code: expectedCode(), declared: validateDeclared(declared) } };
  return { ...body, sha256: sha256(canonicalJson(body)) };
}

// ---------------------------------------------------------------------------------------------------
// Drift: the live configuration (services/manifest.js liveSnapshot) against the manifest. Pure.
//
// Against expected.code: every value that has an env override or is fixed in code, compared with what is
// actually in effect. Against expected.declared: the provider per purpose, the local model ids and the
// engine fingerprint. A declared null means "not declared" and is not compared; an engine that has not
// been OBSERVED yet (no call has landed since boot) is not compared either — unobserved is not drift,
// and live.last_seen shows null for it.
//
// Every entry is { key, expected, live }, values redacted (redactDeep): never a URL, host, IP or key.
// This is the RAW drift, for the token-gated GET /manifest. The unauthenticated /health/deep prints
// publicDrift() of it instead.

const get = (obj, keys) => keys.reduce((o, k) => (o == null ? undefined : o[k]), obj);
const same = (a, b) => JSON.stringify(a ?? null) === JSON.stringify(b ?? null);

function codeComparisons(code) {
  const out = [
    ['decoding.evaluate.temperature', code?.decoding?.evaluate?.temperature],
    ['decoding.evaluate.max_tokens', code?.decoding?.evaluate?.max_tokens],
    ['decoding.shadow.temperature', code?.decoding?.shadow?.temperature],
    ['decoding.shadow.max_tokens', code?.decoding?.shadow?.max_tokens?.default],
    ['decoding.criteria.temperature', code?.decoding?.criteria?.temperature],
    ['decoding.criteria.max_tokens', code?.decoding?.criteria?.max_tokens],
    ['decoding.discuss.temperature', code?.decoding?.discuss?.temperature],
    ['decoding.discuss.max_tokens', code?.decoding?.discuss?.max_tokens?.default],
    ['decoding.chat.temperature', code?.decoding?.chat?.temperature],
    ['decoding.chat.fast_max_tokens', code?.decoding?.chat?.fast?.max_tokens?.default],
    ['decoding.chat.deep_max_tokens', code?.decoding?.chat?.deep?.max_tokens?.default],
    ['decoding.chat.evidence_line_max_tokens', code?.decoding?.chat?.evidence_line?.max_tokens],
    ['consistency.evaluate_mode', code?.consistency?.evaluate?.mode?.default],
    ['consistency.max_sum_delta', code?.consistency?.agree?.max_sum_delta?.default],
    ['consistency.json_retries', code?.consistency?.evaluate?.json_retries?.default],
    ['consistency.shadow_mode', code?.consistency?.shadow?.mode?.default],
    ['models.anthropic', code?.anthropic?.model],
  ];
  for (const name of Object.keys(POLICY.LOCAL_INSTANCES)) {
    out.push([`decoding.num_ctx.${name}`, code?.decoding?.num_ctx?.[name]?.default]);
    out.push([`thinking_style.${name}`, code?.thinking?.style?.[name]?.default]);
  }
  return out;
}

function driftOf(manifest, live) {
  const drift = [];
  const push = (key, expected, actual) => drift.push(redactDeep({ key, expected: expected ?? null, live: actual ?? null }));
  const code = manifest?.expected?.code;
  if (code) {
    for (const [key, expected] of codeComparisons(code)) {
      const actual = get(live, key.split('.'));
      if (!same(expected, actual)) push(`code.${key}`, expected, actual);
    }
  }
  const declared = manifest?.expected?.declared;
  if (declared) {
    for (const [purpose, expected] of Object.entries(declared.providers ?? {})) {
      if (expected == null) continue;
      const actual = live?.providers?.[purpose];
      if (!same(expected, actual)) push(`declared.providers.${purpose}`, expected, actual);
    }
    for (const name of Object.keys(POLICY.LOCAL_INSTANCES)) {
      const inst = declared[name];
      if (!inst) continue;
      if (inst.model != null && !same(inst.model, live?.models?.[name])) push(`declared.${name}.model`, inst.model, live?.models?.[name]);
      const seen = live?.last_seen?.[name];
      if (!seen) continue;   // not observed since boot: nothing to compare
      if (inst.model != null && seen.model != null && !same(inst.model, seen.model)) push(`declared.${name}.served_model`, inst.model, seen.model);
      if (inst.engine != null && !same(inst.engine, seen.engine)) push(`declared.${name}.engine`, inst.engine, seen.engine);
      if (inst.system_fingerprint != null && !same(inst.system_fingerprint, seen.runtime)) push(`declared.${name}.system_fingerprint`, inst.system_fingerprint, seen.runtime);
    }
  }
  return drift;
}

// ---------------------------------------------------------------------------------------------------
// The PUBLIC form of the drift, for the unauthenticated /health/deep. A live value an operator or a server
// supplied as free text — a configured model id (<prefix>MODEL), the model id and system_fingerprint a
// server reported, any string that is not a fixed vocabulary — is never printed there: it becomes
//   { key, expected, live_present, live_sha256_12 }   (the first 12 hex of sha256 of the value, or null)
// which still says THAT it differs, and lets anyone holding the value confirm WHICH, without publishing
// it. A value from a fixed vocabulary (a provider name, a consistency mode, a thinking style, a known
// engine), a number, a boolean or null stays { key, expected, live }. `expected` is always shown: it
// comes from the code or from the declared file, which validateDeclared has already vetted. The raw
// drift stays on the token-gated GET /manifest.

const sha12 = (v) => sha256(typeof v === 'string' ? v : JSON.stringify(v)).slice(0, 12);

// Keys whose live value is free text by nature: opaque whatever it holds, null included.
const OPAQUE_KEYS = [/^declared\.[^.]+\.(?:model|served_model|system_fingerprint)$/, /^code\.models\./];
// Keys whose live value is a fixed vocabulary: shown raw only when it IS one of the vocabulary.
const VOCABULARY = [
  [/^declared\.providers\./, [...POLICY.PROVIDER_NAMES, ...POLICY.EMBED_PROVIDER_NAMES]],
  [/^declared\.[^.]+\.engine$/, [...POLICY.KNOWN_ENGINES]],
  [/^code\.consistency\.(?:evaluate_mode|shadow_mode)$/, [...C.MODES]],
  [/^code\.thinking_style\./, [...TC.THINKING_STYLES, 'invalid']],
];

function publicEntry({ key, expected, live }) {
  const opaque = () => ({ key, expected, live_present: live != null, live_sha256_12: live == null ? null : sha12(live) });
  if (OPAQUE_KEYS.some((re) => re.test(key))) return opaque();
  if (live === null || typeof live === 'number' || typeof live === 'boolean') return { key, expected, live };
  const vocab = VOCABULARY.find(([re]) => re.test(key))?.[1];
  return vocab && vocab.includes(live) ? { key, expected, live } : opaque();   // default-deny any other string
}

function publicDrift(drift) {
  return (drift || []).map((d) => redactDeep(publicEntry(d)));
}

// Read and verify a manifest file. Never throws: a missing or broken file is a finding to report.
//   file 'missing'  — not there
//   file 'invalid'  — not JSON, or its sha256 field is not the hash of its content
//   file 'present'  — parsed and verified
// `sha256` is the VERIFIED content address and nothing else: null unless the file is present and its
// stored hash is the hash of its content, so a hand-edited file can never be vouched for by the hash it
// carries. What the file CLAIMS is `claimed_sha256` — the stored value, when it is 64 hex characters,
// else null (it is printed on /health/deep, so an arbitrary string in that field is not repeated).
const claimed = (m) => (typeof m?.sha256 === 'string' && /^[0-9a-f]{64}$/.test(m.sha256) ? m.sha256 : null);
function readManifest(file = MANIFEST_FILE) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch { return { file: 'missing', manifest: null, sha256: null, claimed_sha256: null, error: null }; }
  let manifest;
  // Not the parser's message: V8 quotes a slice of the text in it, and this reason is printed on /health/deep.
  try { manifest = JSON.parse(text); } catch { return { file: 'invalid', manifest: null, sha256: null, claimed_sha256: null, error: 'not JSON' }; }
  let computed = null;
  try { computed = manifestSha256(manifest); } catch (e) { return { file: 'invalid', manifest, sha256: null, claimed_sha256: claimed(manifest), error: e.message }; }
  if (manifest?.sha256 !== computed) {
    return { file: 'invalid', manifest, sha256: null, claimed_sha256: claimed(manifest), error: 'its sha256 is not the hash of its content' };
  }
  return { file: 'present', manifest, sha256: computed, claimed_sha256: computed, error: null };
}

function readDeclared(file = DECLARED_FILE) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

