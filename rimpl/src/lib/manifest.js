'use strict';

// The model manifest (CCME R2, docs/ARCHITECTURE-MAPPING-CCME.md): one content-addressed file,
// rimpl/src/model-manifest.json, that says which models, prompts, rubric, decoding, routing and
// thinking policy this build of rimpl runs, and which deployment it is meant to run in.
//
//   expected.code      COMPUTED from the code — prompt labels and hashes, the evaluator prompt_version
//                      per provider, the rubric, decoding DEFAULTS with the env var that may override each,
//                      the consistency rule, the router, the thinking policy, the provider policy, the
//                      pinned Anthropic model. Code stays the single source: nothing here is typed twice.
//   expected.declared  READ from rimpl/src/model-manifest.declared.json, hand-maintained: the TARGET
//                      deployment (local evaluator / tutor model ids, the engine fingerprint, the provider
//                      intended per purpose). It is a statement of intent, not a measurement.
//   sha256             sha256 of canonicalJson() of the manifest WITHOUT this field.
//
// Generated by scripts/manifest/build.mjs; CI runs `build.mjs --check` in a scrubbed env and fails if the
// committed file differs from what the code generates. At runtime services/manifest.js loads it and
// reports drift between it and the live configuration on /health/deep (warn-only) and GET /manifest.
//
// PACKAGE-FREE ON PURPOSE: Node built-ins and rimpl's own package-free libs only (the same rule as
// lib/composite.js, lib/thinking-control.js, services/router.js). The CI job that checks the file has no
// `npm install`. The file carries no timestamp, no process.version and no env value, so the same code
// always generates the same bytes. NEVER put a URL, host, IP or key in it: /health/deep is
// unauthenticated, and the declared input is refused if it contains one (validateDeclared).
