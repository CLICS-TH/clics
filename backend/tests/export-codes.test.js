// The de-identified research export is the protocol-facing artifact (CLICS §7/§9): sessions must be
// keyed by the PLE-NNN study pseudonym, auditors by EXP-NNN, and the experimental-design fields
// (episode/Socratic) must travel with each row for the Socratic-effect analysis.
jest.mock('../src/lib/supabase', () => require('./helpers/supabase-mock').makeSupabaseMock());

const request = require('supertest');
const express = require('express');
const { __mock: m } = require('../src/lib/supabase');

const app = express();
app.use(express.json());
app.use('/admin', require('../src/routes/admin'));
const auth = (r) => r.set('Authorization', 'Bearer t');

const SUPER = { id: 'sa', role: 'superadmin', council_id: null, status: 'active', email: 'sa@test' };

beforeEach(() => {
  m.reset();
  m.state.caller = SUPER;
  m.state.resolve = (table, kind, ctx) => {
    if (table === 'ples') return { data: [{
      id: 'u1', ple_code: 'PLE-001', physician_id: 'phys-1', episode_number: 2,
      socratic_active: true, socratic_reason: 'cle2_examiner', status: 'ple_pass',
      is_test: false, turn_count: 4, token_count: 1000, duration_seconds: 1000, started_at: '2026-01-01T00:00:00Z',
    }], count: 1 };
    if (table === 'professionals') {
      // Two distinct professionals reads: physician pseudonyms vs auditor exp_codes.
      return String(ctx.selectArgs?.[0] ?? '').includes('exp_code')
        ? [{ id: 'aud-1', exp_code: 'EXP-001' }]
        : [{ id: 'phys-1', pseudonym: 'P-001' }];
    }
    if (table === 'ai_evaluations') return [];
    if (table === 'audit_scores') return [{
      ple_id: 'u1', auditor_id: 'aud-1', composite_score: 80, d1: 4, d2: 4, d3: 4, d4: 4, d5: 4, d6: 4, d7: 4,
      scored_at: '2026-01-02T00:00:00Z', notes: 'DDx narrowed late',
      d1_anchor: 'clear', d3_anchor: 'ambiguous',
      // d2/d4-d7 anchors absent, and one attestation absent — the MISSING cases the export must
      // distinguish from a recorded 'no'.
      attestations: { all_domains_scored: true, scored_independently: false },
    }];
    return undefined;
  };
});

test('export keys sessions by PLE-NNN + EXP-NNN and carries the experimental fields', async () => {
  const r = await auth(request(app).get('/admin/export'));
  expect(r.status).toBe(200);
  const s = r.body.sessions[0];
  expect(s.ple_code).toBe('PLE-001');
  expect(s.physician).toBe('P-001');               // physician pseudonym, never a name
  expect(s.episode_number).toBe(2);
  expect(s.socratic_active).toBe(true);
  expect(s.socratic_reason).toBe('cle2_examiner');
  expect(s.auditor_scores[0].auditor).toBe('EXP-001'); // EXP-NNN, not A-<hash>
});

// The workshop's whole output is "which anchor needs rewriting", and that question is unanswerable
// from composites alone. Anchors, notes and attestations are stored on every submission and were
// silently dropped by both export handlers until 2026-09-06 — by which time the only human cohort
// in existence had already been collected without them.
test('export carries anchor clarity, notes and attestations per auditor', async () => {
  const r = await auth(request(app).get('/admin/export'));
  expect(r.status).toBe(200);
  const a = r.body.sessions[0].auditor_scores[0];

  expect(a.d1_anchor).toBe('clear');
  expect(a.d3_anchor).toBe('ambiguous');
  expect(a.notes).toBe('DDx narrowed late');
  expect(a.scored_at).toBe('2026-01-02T00:00:00Z');

  // An anchor the rater never answered is null, not '' and not a guess.
  expect(a.d2_anchor).toBeNull();

  // The distinction that matters: declined is false, never-asked is null. Flattening the second to
  // false would assert a confirmation the rater was never shown.
  expect(a.attestations.all_domains_scored).toBe(true);
  expect(a.attestations.scored_independently).toBe(false);
  expect(a.attestations.no_identifiers_found).toBeNull();

  // Every approved attestation key is present, so a consumer can tell "absent" from "not a field".
  expect(Object.keys(a.attestations).sort())
    .toEqual(require('../src/lib/schemas').SCORE_ATTESTATIONS.slice().sort());
});

// The XLSX is the artifact a workshop coordinator actually opens, and it is generated by a second,
// independent handler — the JSON test above proves nothing about it. Assert the columns exist and
// that "never answered" stays visibly empty rather than becoming a 'no'.
test('xlsx Auditor scores sheet carries anchors, attestations and notes', async () => {
  const ExcelJS = require('exceljs');
  const r = await auth(request(app).get('/admin/export.xlsx')).buffer().parse((res, cb) => {
    const chunks = [];
    res.on('data', (c) => chunks.push(c));
    res.on('end', () => cb(null, Buffer.concat(chunks)));
  });
  expect(r.status).toBe(200);

  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(r.body);
  const ws = wb.getWorksheet('Auditor scores');
  const headers = ws.getRow(1).values.slice(1);

  expect(headers).toContain('D1 anchor');
  expect(headers).toContain('D7 anchor');
  expect(headers).toContain('Notes');
  for (const k of require('../src/lib/schemas').SCORE_ATTESTATIONS) {
    expect(headers).toContain(k.replace(/_/g, ' '));
  }
  // Anchor sits immediately after its own domain, not in a block at the end.
  expect(headers[headers.indexOf('D1') + 1]).toBe('D1 anchor');

  const cell = (h) => ws.getRow(2).getCell(headers.indexOf(h) + 1).value;
  expect(cell('D1 anchor')).toBe('clear');
  expect(cell('D3 anchor')).toBe('ambiguous');
  expect(cell('Notes')).toBe('DDx narrowed late');
  expect(cell('all domains scored')).toBe('yes');
  expect(cell('scored independently')).toBe('no');
  // Never asked -> empty cell, which must not read as a declined confirmation.
  expect(cell('no identifiers found') ?? '').toBe('');
  expect(cell('D2 anchor') ?? '').toBe('');
});
