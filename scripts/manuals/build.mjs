#!/usr/bin/env node
/*
 * Build the manuals from their single source.
 *
 *   docs/manuals/content/{physician,auditor}.{th,en}.md
 *        -> physician-ui/public/manual.html        (generated, committed)
 *        -> audit-dashboard/lib/manual-content.ts  (generated, committed)
 *
 * WHY GENERATED-AND-COMMITTED. The portal has no build step — Vercel serves public/ as-is — so the
 * page has to exist on disk. That is the same bargain the portal already makes with its <head>,
 * which is hand-duplicated across five files for the same reason. The difference is that this copy
 * is mechanical and CI asserts it is current (`--check`), so it cannot drift the way the three print
 * guides drifted two months behind the product.
 *
 *   node scripts/manuals/build.mjs           # write the targets
 *   node scripts/manuals/build.mjs --check   # fail if a target is out of date (CI)
 *
 * The A4 PDF target is a separate step (scripts/manuals/generate.mjs) because it needs Playwright.
 */
import { readFile, writeFile, mkdir, copyFile, readdir } from 'node:fs/promises';
