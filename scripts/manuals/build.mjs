/**
 * The dashboard's copy — data, not markup.
 *
 * app/manual/page.tsx renders this as React. Handing it HTML would force
 * dangerouslySetInnerHTML, which components/Markdown.tsx exists specifically to avoid.
 */
function dashboardModule({ th, en }) {
  const payload = { th, ...(en ? { en } : {}) };
  return `// ${GENERATED}\n`
    + '//\n'
    + '// Rendered by app/manual/page.tsx. It is DATA, not markup, so the page can build real React\n'
    + '// elements — the dashboard never injects HTML (see components/Markdown.tsx).\n'
    + "import type { ManualContent } from './manual-types';\n\n"
    + `export const AUDITOR_MANUAL: ManualContent = ${JSON.stringify(payload, null, 2)} as const;\n`;
}

// Where the authored `img/x.png` actually lands, per target.
const IMG_SRC_DIR = 'docs/manuals/source/img';
const PORTAL_IMG_DIR = 'physician-ui/public/img/manual';
const PORTAL_IMG_URL = '/img/manual';
// The dashboard is a separate deployment and serves its own static files, so an auditor figure has
// to be copied there too. Referencing the portal's copy across origins would 404 in production.
const DASH_IMG_DIR = 'audit-dashboard/public/img/manual';
const DASH_IMG_URL = '/img/manual';

/**
 * Rewrite every figure src to an absolute URL for this target, and refuse to build if the file is
 * not there.
 *
 * A relative src resolves against the PAGE, so "img/login.png" means /img/login.png at /manual and
 * something else entirely in the print render — and a missing image is invisible to every gate we
 * have, because it still occupies layout and still exposes its alt text. So the existence check is
 * the only thing standing between a typo and a manual full of grey boxes.
 */
async function resolveImages(sections, urlBase, available, used) {
  for (const s of sections) {
    for (const b of s.blocks) {
      if (b.t !== 'figure') continue;
      const file = basename(b.src);
      if (!available.has(file)) {
        throw new Error(`${s.id}: figure "${b.src}" is not in ${IMG_SRC_DIR}/`
          + `\n  available: ${[...available].join(', ') || '(none)'}`);
      }
      b.src = `${urlBase}/${file}`;
      used.add(file);   // only what this manual REFERENCES gets shipped with it
    }
  }
  return sections;
}

async function listImages() {
  try { return new Set((await readdir(join(ROOT, IMG_SRC_DIR))).filter((f) => !f.startsWith('.'))); }
  catch { return new Set(); }
}

/** Copy the screenshots next to the page that references them. */
async function copyImages(destDir, files, results) {
  await mkdir(join(ROOT, destDir), { recursive: true });
  for (const f of files) {
    const to = join(destDir, f);
    // Compared as BUFFERS. Reading a PNG as utf8 and re-encoding it mangles every byte above 0x7f,
    // so a utf8 round-trip reports every image as changed on every run — which is exactly what a
    // freshness check must not do, because a gate that always fails gets switched off.
    const src = await readFile(join(ROOT, IMG_SRC_DIR, f));
    const dst = await readFile(join(ROOT, to)).catch(() => null);
    if (dst && dst.equals(src)) continue;
    if (CHECK) { results.push({ relPath: to, state: 'stale' }); continue; }
    await copyFile(join(ROOT, IMG_SRC_DIR, f), join(ROOT, to));
    results.push({ relPath: to, state: 'copied' });
  }
}

async function readIf(path) {
  try { return await readFile(join(ROOT, path), 'utf8'); } catch { return null; }
}

/** Write, or under --check report a stale target instead. */
async function emit(relPath, content, results) {
  const abs = join(ROOT, relPath);
  const existing = await readIf(relPath);
  if (existing === content) { results.push({ relPath, state: 'current' }); return; }
  if (CHECK) { results.push({ relPath, state: existing == null ? 'missing' : 'stale' }); return; }
  await writeFile(abs, content, 'utf8');
  results.push({ relPath, state: existing == null ? 'created' : 'updated' });
}

const results = [];

// --- physician -> the portal page --------------------------------------------------------------
const images = await listImages();
const phTh = await readIf('docs/manuals/content/physician.th.md');
if (phTh) {
  const m = parseManual({ th: phTh, en: await readIf('docs/manuals/content/physician.en.md'), name: 'physician' });
  const usedPh = new Set();
  for (const lang of Object.keys(m)) await resolveImages(m[lang], PORTAL_IMG_URL, images, usedPh);
  await copyImages(PORTAL_IMG_DIR, usedPh, results);
  await emit('physician-ui/public/manual.html', portalPage(m), results);
}

// --- auditor -> the dashboard module ------------------------------------------------------------
const auTh = await readIf('docs/manuals/content/auditor.th.md');
if (auTh) {
  const m = parseManual({ th: auTh, en: await readIf('docs/manuals/content/auditor.en.md'), name: 'auditor' });
  // The auditor branch used to skip both of these, so an auditor figure kept its RELATIVE src and
  // rendered as a grey box in the console while printing correctly in the PDF — a defect visible
  // only in one of the two targets, which is the hardest kind to notice.
  const usedAu = new Set();
  for (const lang of Object.keys(m)) await resolveImages(m[lang], DASH_IMG_URL, images, usedAu);
  await copyImages(DASH_IMG_DIR, usedAu, results);
  await emit('audit-dashboard/lib/manual-content.ts', dashboardModule(m), results);
}

if (!results.length) {
  console.error('No content files found under docs/manuals/content/.');
  process.exit(2);
}

const bad = results.filter((r) => r.state === 'stale' || r.state === 'missing');
for (const r of results) {
  const mark = bad.includes(r) ? `${C.red}✗${C.reset}` : `${C.green}✓${C.reset}`;
  console.log(`  ${mark} ${r.relPath} ${C.dim}${r.state}${C.reset}`);
}
if (bad.length) {
  console.error(`\n${C.red}${C.bold}${bad.length} generated file(s) are out of date.${C.reset}`
    + `\n${C.dim}Run \`npm run manuals\` and commit the result. Editing the generated file directly`
    + `\nwill be overwritten — the source is docs/manuals/content/.${C.reset}\n`);
  process.exit(1);
}
