#!/usr/bin/env node
// The text the phone result page explains each step with: for every admitted case in every event pool, its teaser and
// each bank's questions and option labels and lines, all reviewed text the kiosk already shows (ADRs 0005, 0006).
// No tiers and no default trios: the result link carries each step's tier, so the files are no answer key.
// The page has no network (connect-src 'none'), so it imports /booth-steps/<case_id>@<version>.js as a script ('self').
// One file per case version, append-only like backend/src/booth-cases/<EVENT>/versions/: a kept link names the version
// it was played on, so an edited, re-reviewed or retired case never relabels or blanks an old link. Never delete one.
//
//   node scripts/booth/step-text.mjs           exit 1 when an admitted version's file is missing or differs
//   node scripts/booth/step-text.mjs --write   add the admitted versions' files to physician-ui/public/booth-steps/
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const CASES = path.join(ROOT, 'backend/src/booth-cases');
export const OUT = path.join(ROOT, 'physician-ui/public/booth-steps');

const bank = (b) => ({
  variants: Object.fromEntries(b.variants.map((v) => [v.id, v.question])),
  options: Object.fromEntries(b.options.map((o) => [o.id, { label: o.label, line: o.line }])),
});

/** One case's step text file, its teaser and every bank's questions, labels and lines. Pure, so the harness can serve
 *  its fixture cases' text without the backend's dependencies. */
export function stepTextFile(kase, from) {
  const banks = Object.fromEntries(Object.entries(kase.banks).map(([step, level]) => [step,
    step === 'step1' ? bank(level) : Object.fromEntries(Object.entries(level).map(([key, b]) => [key, bank(b)]))]));
  const body = { case_id: kase.case_id, version: kase.version, teaser: kase.teaser, banks };
  return `// Generated by scripts/booth/step-text.mjs from ${from}; do not edit.\nexport default ${JSON.stringify(body, null, 1)};\n`;
}

/** @returns {Map<string, string>} file name -> contents, one per admitted case across every event folder */
export function stepTextFiles() {
  const { readEventFiles, eventPool } = require(path.join(CASES, 'event-pool.js'));
  const files = new Map();
  const events = readdirSync(CASES, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);
  for (const code of events) {
    for (const kase of eventPool(code, readEventFiles(CASES, code)).cases) {
      const name = `${kase.case_id}@${kase.version}.js`;
      if (files.has(name)) throw new Error(`case_id ${kase.case_id} is in two event pools; the result link names a case by its id alone`);
      files.set(name, stepTextFile(kase, `${code}/${kase.case_id}.json`));
    }
  }
  return files;
}

/** @returns {string[]} the admitted versions whose file is missing or differs, empty when all match. A file of a
 *  version no longer admitted is kept on purpose (old links read it) and is not a problem. */
export function stepTextProblems() {
  const want = stepTextFiles();
  const have = existsSync(OUT) ? readdirSync(OUT).filter((f) => f.endsWith('.js')) : [];
  const problems = [];
  for (const [name, text] of want) {
    if (!have.includes(name)) problems.push(`${name} is missing`);
    else if (readFileSync(path.join(OUT, name), 'utf8') !== text) problems.push(`${name} is stale`);
  }
  return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    const want = stepTextFiles();
    mkdirSync(OUT, { recursive: true });
    for (const [name, text] of want) writeFileSync(path.join(OUT, name), text);
    console.log(`wrote ${want.size} admitted versions to ${path.relative(ROOT, OUT)}/ (older versions kept)`);
  } else {
    const problems = stepTextProblems();
    for (const p of problems) console.log(p);
    if (problems.length) { console.log('run: node scripts/booth/step-text.mjs --write'); process.exit(1); }
    console.log('booth-steps match the case files');
  }
}
